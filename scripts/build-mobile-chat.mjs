#!/usr/bin/env node
/*
CDXC:SessionChatMobileWebview 2026-07-31:
Bundles mobile-chat/session-chat-main.tsx (the shared Session Chat page the
React Native app hosts in a webview) into ONE self-contained HTML document and
writes it as a generated TypeScript module inside the mobile submodule. The
app imports that string and feeds it to react-native-webview as
`source={{ html }}`, which sidesteps every platform difference around
bundled file:// assets on iOS and Android. Run after changing sidebar/chat UI,
sidebar styles, or the mobile-chat entry:

  bun run build:mobile-chat
*/

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import * as esbuild from "esbuild";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const entry = path.join(repoRoot, "mobile-chat", "session-chat-main.tsx");
const outFile = path.join(repoRoot, "mobile", "src", "chat", "session-chat-html.generated.ts");

const result = await esbuild.build({
  bundle: true,
  define: { "process.env.NODE_ENV": '"production"' },
  entryPoints: [entry],
  format: "iife",
  jsx: "automatic",
  // Inline every url() asset so the single HTML document has no external
  // references (webview html sources have no usable base URL).
  loader: {
    ".png": "dataurl",
    ".svg": "dataurl",
    ".ttf": "dataurl",
    ".woff": "dataurl",
    ".woff2": "dataurl",
  },
  minify: true,
  outdir: "out",
  target: ["safari16", "chrome110"],
  write: false,
});

let js = "";
let css = "";
for (const file of result.outputFiles) {
  if (file.path.endsWith(".js")) js += file.text;
  else if (file.path.endsWith(".css")) css += file.text;
}
if (!js) {
  throw new Error("esbuild produced no JS output for the mobile chat page.");
}

// </script>-shaped strings inside generated JS would end the inline script tag.
const inlineJs = js.replace(/<\/script>/gi, "<\\/script>");
const inlineCss = css.replace(/<\/style>/gi, "<\\/style>");

const html = `<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0, maximum-scale=1.0, user-scalable=no, viewport-fit=cover" />
    <title>Ghostex Session Chat</title>
    <style>
      html,
      body {
        background: #0e0e0e;
        height: 100%;
        margin: 0;
        overscroll-behavior: none;
        -webkit-text-size-adjust: 100%;
      }
    </style>
    <style>${inlineCss}</style>
  </head>
  <body>
    <div id="root"></div>
    <script>${inlineJs}</script>
  </body>
</html>
`;

const banner = `// GENERATED by scripts/build-mobile-chat.mjs in the Ghostex main repo — do not
// edit by hand. Source: mobile-chat/session-chat-main.tsx plus the shared
// sidebar/chat UI. Regenerate with \`bun run build:mobile-chat\` there.

// eslint-disable-next-line @typescript-eslint/no-inferrable-types
export const SESSION_CHAT_HTML: string = ${JSON.stringify(html)
  .replace(/\u2028/g, "\\u2028")
  .replace(/\u2029/g, "\\u2029")};
`;

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, banner);
const sizeKb = Math.round(Buffer.byteLength(banner) / 1024);
console.log(
  `Wrote ${path.relative(repoRoot, outFile)} (${sizeKb} KiB; js ${Math.round(js.length / 1024)} KiB, css ${Math.round(css.length / 1024)} KiB).`,
);
